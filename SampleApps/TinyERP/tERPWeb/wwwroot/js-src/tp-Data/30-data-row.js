// ● data row
/**
 * Represents a data row.
 * Serialized rows carry only State and Data. Column names and metadata belong to tp.DataTable.Columns.
 */
tp.DataRow = class {
    // ● constructor
    /**
     * Creates a data row.
     * @param {tp.DataTable} Table The owner table.
     * @param {object[]|object|null|undefined} Source The row data array or a source object with Data and State.
     */
    constructor(Table, Source) {
        this.Table = Table || null;
        this.Data = [];
        this.State = tp.DataRowState.Detached;
        this.Assign(Source);
        this.NormalizeDataLength();
        this.ApplyDefaultValues();
        this.ApplyAutoGeneratedKey();
        if (this.Table && !this.Table.Batch && tp.IsFunction(this.Table.OnRowCreated))
            this.Table.OnRowCreated(this);
    }

    // ● static
    /**
     * Normalizes a row state value.
     * @param {number|string|null|undefined} Value The value to normalize.
     * @returns {number} Returns a tp.DataRowState value.
     */
    static NormalizeState(Value) {
        if (tp.IsNumber(Value))
            return tp.ToInt(Value);
        if (tp.IsString(Value) && Object.prototype.propertyIsEnumerable.call(tp.DataRowState, Value))
            return tp.DataRowState[Value];
        return tp.DataRowState.Detached;
    }
    /**
     * Normalizes a row value received from JSON.
     * @param {*} Value The source value.
     * @returns {*} Returns the normalized value.
     */
    static NormalizeJsonValue(Value) {
        if (tp.IsPlainObject(Value) && Object.keys(Value).length === 0)
            return null;
        return Value;
    }
    /**
     * Normalizes row data received from JSON.
     * @param {*[]} Data The source data.
     * @returns {*[]} Returns the normalized data.
     */
    static NormalizeJsonData(Data) {
        var Result;
        var Index;
        if (!tp.IsArray(Data))
            return [];
        Result = Data.slice();
        for (Index = 0; Index < Result.length; Index++)
            Result[Index] = tp.DataRow.NormalizeJsonValue(Result[Index]);
        return Result;
    }

    // ● protected
    /**
     * Normalizes this row data length to the owner table column count.
     * @returns {void}
     */
    NormalizeDataLength() {
        if (this.Table && tp.IsArray(this.Table.Columns))
            this.Data.length = this.Table.Columns.length;
    }
    /**
     * Applies default column values.
     * @returns {void}
     */
    ApplyDefaultValues() {
        var Index;
        var Column;
        if (!this.Table || !tp.IsArray(this.Table.Columns))
            return;
        for (Index = 0; Index < this.Table.Columns.length; Index++) {
            Column = this.Table.Columns[Index];
            if (!tp.IsNil(Column.DefaultValue) && tp.IsEmpty(this.Data[Index]))
                this.Data[Index] = this.NormalizeDefaultValue(Column.DefaultValue, Column);
        }
    }
    /**
     * Converts a column default value to the column data type when possible.
     * @param {*} Value The default value.
     * @param {tp.DataColumn} Column The data column.
     * @returns {*} Returns the normalized value.
     */
    NormalizeDefaultValue(Value, Column) {
        if (!(Column instanceof tp.DataColumn) || !tp.IsString(Value) || tp.IsBlank(Value))
            return Value;
        if (Column.DataType === tp.DataType.String || Column.DataType === tp.DataType.TextBlob)
            return Value;
        try {
            return Column.Parse(Value);
        } catch (e) {
            return Value;
        }
    }
    /**
     * Applies an auto-generated key value when configured by the owner table.
     * @returns {void}
     */
    ApplyAutoGeneratedKey() {
        var Index;
        var Column;
        var Value;
        if (!this.Table || this.Table.AutoGenerateGuidKeys !== true || !tp.IsFunction(tp.Guid))
            return;
        Index = this.Table.KeyFieldIndex;
        if (!tp.IsNumber(Index) || Index < 0 || !tp.IsArray(this.Table.Columns))
            return;
        Column = this.Table.Columns[Index];
        if (!(Column instanceof tp.DataColumn) || Column.DataType !== tp.DataType.String)
            return;
        Value = this.Data[Index];
        if (tp.IsEmpty(Value) || (tp.IsString(Value) && tp.IsBlank(Value)))
            this.SetByIndex(Index, tp.Guid());
    }

    // ● public
    /**
     * Assigns values from a source object.
     * @param {object[]|object|null|undefined} Source The source object or data array.
     * @returns {void}
     */
    Assign(Source) {
        if (tp.IsArray(Source)) {
            this.Data = tp.DataRow.NormalizeJsonData(Source);
            return;
        }
        if (tp.IsObject(Source)) {
            this.Data = tp.DataRow.NormalizeJsonData(Source.Data);
            this.State = tp.DataRow.NormalizeState(Source.State);
        }
    }
    /**
     * Returns a plain object used by JSON.stringify().
     * @returns {object} Returns a plain object with State and Data.
     */
    toJSON() {
        return {
            State: this.State,
            Data: this.Data
        };
    }
    /**
     * Returns the value of a column by column index.
     * @param {number} Index The column index.
     * @returns {*} Returns the value.
     */
    GetByIndex(Index) {
        return tp.InRange(this.Data, Index) ? this.Data[Index] : null;
    }
    /**
     * Sets the value of a column by column index.
     * @param {number} Index The column index.
     * @param {*} Value The value to set.
     * @returns {void}
     */
    SetByIndex(Index, Value) {
        var OldValue;
        var Column;
        if (!tp.IsNumber(Index) || Index < 0)
            return;
        OldValue = this.Data[Index];
        if (OldValue === Value)
            return;
        if (this.Table && this.Table.Batch !== true && tp.IsArray(this.Table.Columns)) {
            Column = this.Table.Columns[Index] || null;
            if (tp.IsFunction(this.Table.OnRowModifying))
                this.Table.OnRowModifying(this, Column, OldValue, Value);
            this.Data[Index] = Value;
            if (tp.IsFunction(this.Table.OnRowModified))
                this.Table.OnRowModified(this, Column, OldValue, Value);
        } else {
            this.Data[Index] = Value;
        }
        if (this.State === tp.DataRowState.Unchanged)
            this.State = tp.DataRowState.Modified;
    }
    /**
     * Returns the value of a column by column name.
     * @param {string} Name The column name.
     * @returns {*} Returns the value.
     */
    GetByName(Name) {
        return this.GetByIndex(this.Table ? this.Table.IndexOfColumn(Name) : -1);
    }
    /**
     * Sets the value of a column by column name.
     * @param {string} Name The column name.
     * @param {*} Value The value to set.
     * @returns {void}
     */
    SetByName(Name, Value) {
        this.SetByIndex(this.Table ? this.Table.IndexOfColumn(Name) : -1, Value);
    }
    /**
     * Returns the value of a column by index, name, or column instance.
     * @param {number|string|tp.DataColumn} Column The column index, name, or instance.
     * @param {*} Default The default value.
     * @returns {*} Returns the value.
     */
    Get(Column, Default) {
        var Index = this.Table ? this.Table.IndexOfColumn(Column) : -1;
        var Result = Index >= 0 ? this.Data[Index] : null;
        return !tp.IsEmpty(Result) ? Result : (!tp.IsEmpty(Default) ? Default : null);
    }
    /**
     * Sets the value of a column by index, name, or column instance.
     * @param {number|string|tp.DataColumn} Column The column index, name, or instance.
     * @param {*} Value The value to set.
     * @returns {void}
     */
    Set(Column, Value) {
        this.SetByIndex(this.Table ? this.Table.IndexOfColumn(Column) : -1, Value);
    }
    /**
     * Removes the row from its owner table.
     * @returns {void}
     */
    Remove() {
        if (this.Table && tp.IsFunction(this.Table.RemoveRow))
            this.Table.RemoveRow(this);
    }
    /**
     * Sets the row state to Unchanged.
     * @returns {void}
     */
    AcceptChanges() {
        this.State = tp.DataRowState.Unchanged;
    }
    /**
     * Returns true if a column value is null or undefined.
     * @param {number|string|tp.DataColumn} Column The column index, name, or instance.
     * @returns {boolean} Returns true if the value is null or undefined.
     */
    IsNull(Column) {
        return tp.IsEmpty(this.Get(Column));
    }
    /**
     * Returns true if a column value is null, undefined, or an empty string.
     * @param {number|string|tp.DataColumn} Column The column index, name, or instance.
     * @returns {boolean} Returns true if the value is null or empty.
     */
    IsNullOrEmpty(Column) {
        var Index = this.Table ? this.Table.IndexOfColumn(Column) : -1;
        var Value = Index >= 0 ? this.GetByIndex(Index) : null;
        if (tp.IsEmpty(Value))
            return true;
        return this.Table
            && this.Table.Columns[Index]
            && this.Table.Columns[Index].DataType === tp.DataType.String
            && tp.IsString(Value)
            && tp.IsBlank(Value);
    }
    /**
     * Copies values from a specified source row.
     * @param {tp.DataRow} SourceRow The source row.
     * @param {string[]} ExcludeFieldList Optional field names to exclude.
     * @returns {void}
     */
    CopyFromRow(SourceRow, ExcludeFieldList) {
        var Index;
        var Column;
        if (!(SourceRow instanceof tp.DataRow) || !this.Table || !tp.IsArray(this.Table.Columns))
            return;
        ExcludeFieldList = ExcludeFieldList || [];
        for (Index = 0; Index < this.Table.Columns.length; Index++) {
            Column = this.Table.Columns[Index];
            if (!tp.ListContainsText(ExcludeFieldList, Column.Name))
                this.SetByIndex(Index, SourceRow.GetByIndex(Index));
        }
    }
    /**
     * Copies values from a plain object.
     * @param {object} SourceObject The source object.
     * @param {string[]} ExcludeFieldList Optional field names to exclude.
     * @returns {void}
     */
    FromObject(SourceObject, ExcludeFieldList) {
        var Prop;
        if (!tp.IsObject(SourceObject) || !this.Table)
            return;
        ExcludeFieldList = ExcludeFieldList || [];
        for (Prop in SourceObject) {
            if (Object.prototype.propertyIsEnumerable.call(SourceObject, Prop)
                && this.Table.ContainsColumn(Prop)
                && !tp.ListContainsText(ExcludeFieldList, Prop)) {
                this.Set(Prop, SourceObject[Prop]);
            }
        }
    }
    /**
     * Creates a plain object projection for UI code.
     * This is not the data transfer JSON contract.
     * @returns {object} Returns a column-name/value object with __Row.
     */
    ToObject() {
        var Result = {};
        var Index;
        var Column;
        if (this.Table && tp.IsArray(this.Table.Columns)) {
            for (Index = 0; Index < this.Table.Columns.length; Index++) {
                Column = this.Table.Columns[Index];
                Result[Column.Name] = this.Data[Index];
            }
        }
        Result.__Row = this;
        return Result;
    }
};

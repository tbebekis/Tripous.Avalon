    /**
    Applies explicit create params.
    @protected
    @override
    @param {tp.CreateParams|object|null|undefined} Params The create params.
    */
    ApplyCreateParams(Params) {
        Params = Params || {};
        var DataSourceValue = Params.DataSource;
        var HasDataSource = !tp.IsNil(DataSourceValue);
        var BaseParams = Params;
        if (HasDataSource === true) {
            BaseParams = new tp.CreateParams(Params);
            BaseParams.DataSource = null;
        }
        super.ApplyCreateParams(BaseParams);
        let CP,
            Name,
            Columns,    // []
            A;          // []
        let Column;     // tp.GridColumn

        // columns
        if (tp.IsArray(Params.Columns)) {
            Columns = Params.Columns;
            for (let i = 0, ln = Columns.length; i < ln; i++) {
                CP = Columns[i];
                Name = CP['Name'];
                Column = this.AddColumn(Name);
                Column.ApplyColumnParams(CP);
            }
        }

        if (Columns) {
            this.AutoGenerateColumns = false;
        } else if (!tp.IsNil(Params.AutoGenerateColumns)) {
            this.AutoGenerateColumns = Params.AutoGenerateColumns === true;
        }



        Object.keys(Params).forEach(Prop => {
            if (!tp.IsFunction(Params[Prop])) {
                if ('Columns' === Prop || 'AutoGenerateColumns' === Prop || 'Locators' === Prop || 'DataSource' === Prop) {
                    // do nothing
                } else if (tp.IsSameText('CustomButtons', Prop) && tp.IsArray(Params[Prop])) {
                    A = Params[Prop];
                    for (let i = 0, ln = A.length; i < ln; i++) {
                        CP = A[i];
                        this.AddToolBarButton(CP['Command'] || '', CP['Text'] || '', CP['ToolTip'] || '', CP['IcoClasses'] || '', CP['CssClasses'] || '', CP['ToRight'] === true);
                    }
                } else {
                    this[Prop] = Params[Prop];
                }
            }
        });
        if (HasDataSource === true)
            this.DataSource = DataSourceValue;
    }

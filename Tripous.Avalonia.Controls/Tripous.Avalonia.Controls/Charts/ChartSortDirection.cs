namespace Avalonia.Controls;

/// <summary>
/// Defines category sort direction for a chart projection.
/// </summary>
public enum ChartSortDirection
{
    /// <summary>
    /// Keeps source discovery order.
    /// </summary>
    None,
    /// <summary>
    /// Sorts categories in ascending order.
    /// </summary>
    Ascending,
    /// <summary>
    /// Sorts categories in descending order.
    /// </summary>
    Descending,
}
